model = 'human_detection_navigation_system_v2';
new_system(model);
open_system(model);

%% PARAMETERS
Ts = '0.1';   % sample time

%% INPUTS

add_block('simulink/Sources/Band-Limited White Noise', ...
    [model '/sensor_noise'], ...
    'Position', [30 160 60 190]);

set_param([model '/sensor_noise'], 'Noise power', '1e-4');
set_param([model '/sensor_noise'], 'Sample time', Ts);

add_block('simulink/Math Operations/Add', [model '/measured_distance'], ...
    'Inputs', '++', ...
    'Position', [100 120 130 150]);

%% DELAY + DERIVATIVE

add_block('simulink/Discrete/Unit Delay', [model '/z^-1'], ...
    'SampleTime', Ts, ...
    'Position', [180 120 210 150]);

add_block('simulink/Math Operations/Subtract', ...
    [model '/Difference'], ...
    'Position', [250 120 280 150]);

add_block('simulink/Math Operations/Gain', ...
    [model '/Derivative'], ...
    'Gain', ['1/' Ts], ...
    'Position', [320 120 360 150]);

add_block('simulink/Math Operations/Abs', ...
    [model '/Abs'], ...
    'Position', [390 120 420 150]);

%% THRESHOLDS

add_block('simulink/Sources/Constant', ...
    [model '/Motion_Threshold'], ...
    'Value', '0.05', ...
    'Position', [390 170 420 200]);

add_block('simulink/Logic and Bit Operations/Relational Operator', ...
    [model '/Motion_Detection'], ...
    'Operator', '>', ...
    'Position', [450 120 480 150]);

add_block('simulink/Sources/Constant', ...
    [model '/Distance_Threshold'], ...
    'Value', '0.5', ...
    'Position', [450 200 480 230]);

add_block('simulink/Logic and Bit Operations/Relational Operator', ...
    [model '/Proximity'], ...
    'Operator', '<', ...
    'Position', [520 180 550 210]);

add_block('simulink/Logic and Bit Operations/Logical Operator', ...
    [model '/AND'], ...
    'Operator', 'AND', ...
    'Position', [600 140 630 170]);

%% CONTROL

add_block('simulink/Sources/Constant', ...
    [model '/STOP'], ...
    'Value', '0', ...
    'Position', [600 80 630 110]);

add_block('simulink/Sources/Constant', ...
    [model '/MOVE'], ...
    'Value', '1', ...
    'Position', [600 220 630 250]);

add_block('simulink/Signal Routing/Switch', ...
    [model '/Controller'], ...
    'Threshold', '0.5', ...
    'Position', [680 140 710 180]);

add_block('simulink/Math Operations/Gain', ...
    [model '/Speed'], ...
    'Gain', '2', ...
    'Position', [740 150 780 180]);

add_block('simulink/Sinks/Scope', ...
    [model '/speed_monitor'], ...
    'Position', [820 150 850 180]);

%% MOTION MODEL (CORRECT PHYSICS)

% Angle integrator
add_block('simulink/Continuous/Integrator', ...
    [model '/theta'], ...
    'Position', [820 230 850 260]);

% Trig
add_block('simulink/Math Operations/Trigonometric Function', ...
    [model '/cos'], 'Operator', 'cos', ...
    'Position', [880 210 910 240]);

add_block('simulink/Math Operations/Trigonometric Function', ...
    [model '/sin'], 'Operator', 'sin', ...
    'Position', [880 260 910 290]);

% Velocity scaling
add_block('simulink/Math Operations/Product', ...
    [model '/vx'], ...
    'Position', [940 210 970 240]);

add_block('simulink/Math Operations/Product', ...
    [model '/vy'], ...
    'Position', [940 260 970 290]);

% Position
add_block('simulink/Continuous/Integrator', ...
    [model '/x'], ...
    'Position', [1000 210 1030 240]);

add_block('simulink/Continuous/Integrator', ...
    [model '/y'], ...
    'Position', [1000 260 1030 290]);

% XY Graph
add_block('simulink/Sinks/XY Graph', ...
    [model '/trajectory'], ...
    'Position', [1080 220 1130 280]);

%% CONNECTIONS

add_line(model,'distance_sensor/1','measured_distance/1');
add_line(model,'sensor_noise/1','measured_distance/2');

add_line(model,'measured_distance/1','z^-1/1');
add_line(model,'measured_distance/1','Difference/1');
add_line(model,'z^-1/1','Difference/2');

add_line(model,'Difference/1','Derivative/1');
add_line(model,'Derivative/1','Abs/1');

add_line(model,'Abs/1','Motion_Detection/1');
add_line(model,'Motion_Threshold/1','Motion_Detection/2');

add_line(model,'measured_distance/1','Proximity/1');
add_line(model,'Distance_Threshold/1','Proximity/2');

add_line(model,'Motion_Detection/1','AND/1');
add_line(model,'Proximity/1','AND/2');

add_line(model,'STOP/1','Controller/1');
add_line(model,'AND/1','Controller/2');
add_line(model,'MOVE/1','Controller/3');

add_line(model,'Controller/1','Speed/1');
add_line(model,'Speed/1','speed_monitor/1');

add_line(model,'Speed/1','theta/1');

add_line(model,'theta/1','cos/1');
add_line(model,'theta/1','sin/1');

add_line(model,'cos/1','vx/1');
add_line(model,'Speed/1','vx/2');

add_line(model,'sin/1','vy/1');
add_line(model,'Speed/1','vy/2');

add_line(model,'vx/1','x/1');
add_line(model,'vy/1','y/1');

add_line(model,'x/1','trajectory/1');
add_line(model,'y/1','trajectory/2');

%% SAVE
save_system(model);